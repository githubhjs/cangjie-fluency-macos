#!/usr/bin/perl
# Perl port of cangjie-fluency's tools/cin2rime.py. Output MUST stay byte-identical to the python tool.
# Uses only core modules; written for the perl that ships with macOS (/usr/bin/perl, 5.30-ish).
#
# usage: cin2rime.pl INPUT.cin OUTPUT.dict.yaml [--essay essay.txt]
#
# * only %chardef entries are used; only single-character entries are kept
# * codes are lower-cased; fields are split ONLY on ASCII space/tab (the .cin has a U+3000 after a code)
# * weight = 100000 - rank (rank per code, from 0); WITH --essay: the character's frequency in essay.txt
#   (min 1), clamped below the previous candidate of the same code (keeps .cin order)
# * identical (text, code) pairs are dropped (first wins); output UTF-8, no BOM, LF
#
# The .cin table has no known license: it is downloaded at install time and must never be committed.
use strict;
use warnings;
use utf8;
use Encode qw(decode encode FB_CROAK);

my $HEADER =
    "# encoding: utf-8\n"
  . "# Generated by tools/cin2rime.py from a .cin table. Do not commit this file.\n"
  . "\n"
  . "---\n"
  . "name: cangjie3.base\n"
  . "version: \"1.0\"\n"
  . "sort: by_weight\n"
  . "columns:\n"
  . "  - text\n"
  . "  - code\n"
  . "  - weight\n"
  . "...\n"
  . "\n";

# python: open(path, encoding="utf-8-sig", newline=None).read().split("\n")
# (universal newlines: CRLF and a lone CR both end a line)
sub read_lines {
    my ($path) = @_;
    open(my $fh, '<:raw', $path) or die "cannot open $path: $!\n";
    local $/;
    my $bytes = <$fh>;
    close $fh;
    $bytes = '' unless defined $bytes;
    my $s = decode('UTF-8', $bytes, FB_CROAK);
    $s =~ s/\A\x{FEFF}//;
    $s =~ s/\r\n/\n/g;
    $s =~ s/\r/\n/g;
    return split(/\n/, $s, -1);
}

# single-character frequencies from essay.txt (text<TAB>weight); later lines win
sub load_essay {
    my ($path) = @_;
    my %freq;
    for my $l (read_lines($path)) {
        $l =~ s/\A\r+//;
        $l =~ s/\r+\z//;
        my @p = split(/\t/, $l, -1);
        if (@p == 2 && length($p[0]) == 1 && $p[1] =~ /\A[0-9]+\z/) {
            $freq{ $p[0] } = $p[1] + 0;
        }
    }
    return \%freq;
}

sub usage {
    die "usage: cin2rime.pl INPUT.cin OUTPUT.dict.yaml [--essay essay.txt]\n";
}

my @args = @ARGV;
my $essay;
if (@args == 4 && $args[2] eq '--essay') {
    $essay = load_essay($args[3]);
    @args = @args[0, 1];
}
usage() unless @args == 2;

my %prevw;
my %seen;
my %rank;
my %chars;
my @out;
my $in_chardef = 0;
my ($n_entries, $n_multi, $n_dup, $n_bad) = (0, 0, 0, 0);

for my $raw (read_lines($args[0])) {
    my $line = $raw;
    $line =~ s/\A[ \t\r]+//;
    $line =~ s/[ \t\r]+\z//;
    next if $line eq '';
    if (substr($line, 0, 1) eq '%') {
        my @low = split(/[ \t]+/, lc($line), -1);
        if ($low[0] eq '%chardef' && @low > 1) {
            $in_chardef = ($low[1] eq 'begin') ? 1 : 0;
        }
        next;
    }
    next unless $in_chardef;
    my @parts = split(/[ \t]+/, $line, -1);
    if (@parts < 2) { $n_bad++; next; }
    my $code = lc($parts[0]);
    my $text = $parts[1];
    $n_entries++;
    if (length($text) != 1) { $n_multi++; next; }
    my $key = $text . "\t" . $code;
    if ($seen{$key}) { $n_dup++; next; }
    $seen{$key} = 1;
    $chars{$text} = 1;
    my $r = exists $rank{$code} ? $rank{$code} : 0;
    $rank{$code} = $r + 1;
    my $w;
    if (!defined $essay) {
        $w = 100000 - $r;
    } else {
        $w = exists $essay->{$text} ? $essay->{$text} : 0;
        $w = 1 if $w < 1;
        if (exists $prevw{$code} && $prevw{$code} - 1 < $w) {
            $w = $prevw{$code} - 1;
        }
        $w = 1 if $w < 1;
        $prevw{$code} = $w;
    }
    push @out, sprintf("%s\t%s\t%d\n", $text, $code, $w);
}

open(my $o, '>:raw', $args[1]) or die "cannot write $args[1]: $!\n";
print {$o} encode('UTF-8', $HEADER . join('', @out), FB_CROAK);
close($o) or die "cannot close $args[1]: $!\n";

printf "chardef_entries: %d\n", $n_entries;
printf "multi_char_skipped: %d\n", $n_multi;
printf "duplicates_skipped: %d\n", $n_dup;
printf "malformed_skipped: %d\n", $n_bad;
printf "written: %d\n", scalar(@out);
printf "distinct_chars: %d\n", scalar(keys %chars);
